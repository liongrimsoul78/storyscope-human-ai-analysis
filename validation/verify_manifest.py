#!/usr/bin/env python3
"""Verify MANIFEST_SHA256SUMS.txt with the Python standard library.

Strict mode requires every file under the skill root to be listed in the
manifest, with two deliberate exceptions for entries that never belong to the
published pack:

* the root ``.git`` entry, whether it is a directory (normal checkout) or a
  file (``gitdir:`` pointer of a linked worktree);
* the root ``_export`` directory created by the CI canonical export.

Both exceptions match the exact root entry name only. Look-alike names such as
``archivo.git``, ``docs/.git-example/``, ``_exported/`` or ``docs/_export/``
are still inspected, so an exclusion can never hide project content. Cache
directories (``__pycache__``, ``.pytest_cache``) remain ignored anywhere.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path, PurePosixPath

LINE_RE = re.compile(r"^([0-9a-fA-F]{64})\s{2}(.+?)\s*$")
IGNORED_PARTS = {"__pycache__", ".pytest_cache"}
# Root-only exclusions. `.git` may be a directory (normal checkout) or a file
# (linked worktree pointer). `_export` is excluded only when it really is the
# root directory generated by the CI export step.
IGNORED_ROOT_ENTRIES = {".git"}
EXPORT_DIRECTORY = "_export"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def is_excluded(relative: str, excluded_roots: set[str]) -> bool:
    """Return True only for entries that are not part of the published pack."""
    parts = PurePosixPath(relative).parts
    if not parts:
        return False
    if parts[0] in excluded_roots:
        return True
    return any(part in IGNORED_PARTS for part in parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--strict",
        action="store_true",
        help="also fail when a file under the skill root is not listed in the manifest",
    )
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    manifest = root / "MANIFEST_SHA256SUMS.txt"
    if not manifest.is_file():
        print(f"FAIL: missing manifest: {manifest}")
        return 2

    errors: list[str] = []
    entries: dict[str, str] = {}
    duplicates: list[str] = []
    for number, raw in enumerate(manifest.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        match = LINE_RE.match(line)
        if not match:
            errors.append(f"line {number}: malformed manifest entry: {raw!r}")
            continue
        expected, relative = match.groups()
        if relative in entries:
            duplicates.append(relative)
        entries[relative] = expected.lower()

    if duplicates:
        errors.append(
            "duplicate manifest entries: " + ", ".join(sorted(set(duplicates)))
        )

    for relative, expected in sorted(entries.items()):
        path = root / relative
        if not path.is_file():
            errors.append(f"missing file: {relative}")
            continue
        actual = sha256(path)
        if actual != expected:
            errors.append(f"hash mismatch: {relative} (expected {expected}, found {actual})")

    if args.strict:
        excluded_roots = set(IGNORED_ROOT_ENTRIES)
        if (root / EXPORT_DIRECTORY).is_dir():
            excluded_roots.add(EXPORT_DIRECTORY)
        for path in root.rglob("*"):
            if not path.is_file():
                continue
            relative = path.relative_to(root).as_posix()
            if relative == "MANIFEST_SHA256SUMS.txt":
                continue
            if is_excluded(relative, excluded_roots):
                continue
            if relative not in entries:
                errors.append(f"unlisted file: {relative}")

    if errors:
        for error in errors:
            print(f"FAIL: {error}")
        return 1

    print(f"PASS: {len(entries)} manifest entries verified; 0 failures.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
